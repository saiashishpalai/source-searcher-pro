import OpenAI from 'openai';

/**
 * PRDAssemblyService - Generates standardized PRD documents from conversational answers
 */
export class PRDAssemblyService {
  constructor(apiKey) {
    this.openai = new OpenAI({ apiKey });
    this.llmModel = 'gpt-4o-mini';
  }

  /**
   * Generate final PRD document from user's 5 section answers
   * Uses fixed template with explicit restrictions on which fields GPT can fill
   */
  async generateFinalPRD({ sections, citations = [], supabaseAdmin = null, userId = null }) {
    const systemPrompt = `You are an expert product manager generating a PRD from validated section answers.

You must always generate a PRD in the following format, exactly as shown below.

Never modify or invent metadata values. The following fields are NOT to be generated by you:

- PRD Created On → handled by system (auto date)
- PRD Updated On → handled by system when a new version is saved
- Created By → filled from user profile
- Development Team → left blank for user input
- Design Team → left blank for user input
- Timeline → left blank for user input

Only fill the remaining sections using provided answers and context.

If you lack information for a field, leave it blank but keep the section header intact.

PRD TEMPLATE (Fixed Output Format)
-----------------------------------
Product/Feature Title:

Product Name:

PRD Created On:

PRD Updated On:

Created By:

Development Team:

Design Team:

Objective

Background

Scope

Requirements

Success Metrics

Access Permissions

Notifications

Reporting

Analytics Events

Filters

Dependencies

Backward Compatibility

Release Plan

Timeline
-----------------------------------

Never invent metadata or fill restricted fields.
Always preserve these headings exactly, in this sequence.`;

    // Build user prompt with section answers
    const userPrompt = `### User Responses

Objective: ${sections.objective || ""}

Scope: ${sections.scope || ""}

Metrics: ${sections.metrics || ""}

Dependencies: ${sections.dependencies || ""}

Timeline: ${sections.timeline || ""}

${citations.length > 0 ? `### Context Chunks

${citations.map((c, i) => `[${i + 1}] ${c}`).join("\n")}` : ''}

Generate the PRD document following the exact template above. Fill only the sections you have information for, and leave restricted fields (Created On, Updated On, Created By, Development Team, Design Team, Timeline) blank.`;

    try {
      const completion = await this.openai.chat.completions.create({
        model: this.llmModel,
        temperature: 0.2, // Low temperature for consistency
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: userPrompt }
        ]
      });

      const prdText = completion.choices[0].message.content;

      return {
        prd_text: prdText,
        citations_used: citations
      };
    } catch (error) {
      console.error('PRD assembly error:', error);
      throw new Error(`Failed to generate PRD: ${error.message}`);
    }
  }

  /**
   * Fetch citation chunk contents from database
   */
  async fetchCitationContents(citationIds, supabaseAdmin, userId) {
    if (!citationIds || citationIds.length === 0 || !supabaseAdmin) {
      return [];
    }

    try {
      const { data: chunks, error } = await supabaseAdmin
        .from('document_chunks')
        .select('id, content')
        .in('id', citationIds)
        .eq('user_id', userId)
        .limit(20); // Cap at 20 citations

      if (error) {
        console.error('Error fetching citations:', error);
        return [];
      }

      return (chunks || []).map(chunk => chunk.content || '').filter(Boolean);
    } catch (error) {
      console.error('Error in fetchCitationContents:', error);
      return [];
    }
  }
}

